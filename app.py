import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder, StandardScaler

from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.neighbors import KNeighborsClassifier
from sklearn.naive_bayes import GaussianNB
from sklearn.svm import SVC

from sklearn.metrics import (
    accuracy_score,
    roc_auc_score,
    precision_score,
    recall_score,
    f1_score,
    matthews_corrcoef,
    confusion_matrix,
    classification_report
)

# =====================================================
# PAGE CONFIG
# =====================================================

st.set_page_config(
    page_title="AI Tool Usage Classification",
    page_icon="🤖",
    layout="wide"
)

st.title("🤖 AI Tool Usage Classification")
st.markdown(
"""
### Predict Student Willingness to Pay for AI Tools

Dataset: AI Tool Usage by Indian College Students
"""
)

# =====================================================
# LOAD DATASET
# =====================================================

try:
    df = pd.read_csv("Students.csv")

    st.success("Dataset Loaded Successfully ✅")

except Exception as e:
    st.error(f"Error Loading Dataset: {e}")
    st.stop()

# =====================================================
# DATA PREVIEW
# =====================================================

st.subheader("Dataset Preview")

st.dataframe(df.head())

col1, col2 = st.columns(2)

col1.info(f"Rows: {df.shape[0]}")
col2.info(f"Columns: {df.shape[1]}")

# =====================================================
# DATA PREPROCESSING
# =====================================================

columns_to_drop = [
    "Student_Name",
    "College_Name"
]

for col in columns_to_drop:
    if col in df.columns:
        df.drop(col, axis=1, inplace=True)

df.dropna(inplace=True)

# =====================================================
# ENCODE ALL COLUMNS
# =====================================================

from sklearn.preprocessing import LabelEncoder

for col in df.columns:
    encoder = LabelEncoder()
    df[col] = encoder.fit_transform(df[col].astype(str))

TARGET_COLUMN = "Willing_to_Pay_for_Access"

X = df.drop(TARGET_COLUMN, axis=1)
y = df[TARGET_COLUMN]

print("Feature Data Types:")
print(X.dtypes)

print("\nNon Numeric Columns:")
print(X.select_dtypes(exclude=['int64','float64']).columns)

# =====================================================
# TRAIN TEST SPLIT
# =====================================================

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

# =====================================================
# SCALING
# =====================================================

scaler = StandardScaler()

X_train = scaler.fit_transform(X_train)
X_test = scaler.transform(X_test)

# =====================================================
# MODEL SELECTION
# =====================================================

st.subheader("Select Classification Model")

model_name = st.selectbox(
    "Choose Model",
    [
        "Logistic Regression",
        "Decision Tree",
        "KNN",
        "Naive Bayes",
        "SVM"
    ]
)

# =====================================================
# MODEL CREATION
# =====================================================

if model_name == "Logistic Regression":

    model = LogisticRegression(
        max_iter=1000
    )

elif model_name == "Decision Tree":

    model = DecisionTreeClassifier(
        random_state=42
    )

elif model_name == "KNN":

    model = KNeighborsClassifier(
        n_neighbors=5
    )

elif model_name == "Naive Bayes":

    model = GaussianNB()

else:

    model = SVC(
        probability=True,
        random_state=42
    )

# =====================================================
# TRAIN MODEL
# =====================================================

model.fit(X_train, y_train)

# =====================================================
# PREDICTIONS
# =====================================================

y_pred = model.predict(X_test)

y_prob = model.predict_proba(
    X_test
)[:, 1]

# =====================================================
# METRICS
# =====================================================

accuracy = accuracy_score(
    y_test,
    y_pred
)

auc = roc_auc_score(
    y_test,
    y_prob
)

precision = precision_score(
    y_test,
    y_pred
)

recall = recall_score(
    y_test,
    y_pred
)

f1 = f1_score(
    y_test,
    y_pred
)

mcc = matthews_corrcoef(
    y_test,
    y_pred
)

# =====================================================
# DISPLAY METRICS
# =====================================================

st.subheader("Evaluation Metrics")

row1_col1, row1_col2, row1_col3 = st.columns(3)

row1_col1.metric(
    "Accuracy",
    f"{accuracy:.4f}"
)

row1_col2.metric(
    "AUC",
    f"{auc:.4f}"
)

row1_col3.metric(
    "Precision",
    f"{precision:.4f}"
)

row2_col1, row2_col2, row2_col3 = st.columns(3)

row2_col1.metric(
    "Recall",
    f"{recall:.4f}"
)

row2_col2.metric(
    "F1 Score",
    f"{f1:.4f}"
)

row2_col3.metric(
    "MCC",
    f"{mcc:.4f}"
)

# =====================================================
# CONFUSION MATRIX
# =====================================================

st.subheader("Confusion Matrix")

cm = confusion_matrix(
    y_test,
    y_pred
)

fig, ax = plt.subplots(
    figsize=(5, 4)
)

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    ax=ax
)

ax.set_xlabel("Predicted")
ax.set_ylabel("Actual")

st.pyplot(fig)

# =====================================================
# CLASSIFICATION REPORT
# =====================================================

st.subheader("Classification Report")

report = classification_report(
    y_test,
    y_pred,
    output_dict=True
)

report_df = pd.DataFrame(
    report
).transpose()

st.dataframe(
    report_df,
    use_container_width=True
)

# =====================================================
# FOOTER
# =====================================================

st.markdown("---")
st.markdown(
    "Machine Learning Assignment 2 - Classification Model Comparison"
)

