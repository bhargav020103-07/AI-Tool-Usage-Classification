# =======================================================
# ML Assignment 2
# Dataset: AI Tool Usage by Indian College Students
# Target: Willing_to_Pay_for_Access
# =======================================================

import os
import pandas as pd

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder, StandardScaler

from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.neighbors import KNeighborsClassifier
from sklearn.naive_bayes import GaussianNB
from sklearn.svm import SVC

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    matthews_corrcoef,
    confusion_matrix,
    classification_report
)

import seaborn as sns
import matplotlib.pyplot as plt

# =======================================================
# CREATE FOLDERS
# =======================================================

os.makedirs("results", exist_ok=True)
os.makedirs("confusion_matrices", exist_ok=True)
os.makedirs("classification_reports", exist_ok=True)

# =======================================================
# LOAD DATASET
# =======================================================

df = pd.read_csv("Students.csv")

print("Dataset Loaded Successfully")
print("Shape:", df.shape)

# =======================================================
# DROP UNNECESSARY COLUMNS
# =======================================================

drop_cols = ["Student_Name", "College_Name"]

for col in drop_cols:
    if col in df.columns:
        df.drop(col, axis=1, inplace=True)

# =======================================================
# HANDLE MISSING VALUES
# =======================================================

df.dropna(inplace=True)

# =======================================================
# LABEL ENCODING
# =======================================================

encoders = {}

for col in df.columns:

    if df[col].dtype == "object":

        encoder = LabelEncoder()

        df[col] = encoder.fit_transform(
            df[col].astype(str)
        )

        encoders[col] = encoder

# =======================================================
# FEATURES AND TARGET
# =======================================================

TARGET = "Willing_to_Pay_for_Access"

X = df.drop(TARGET, axis=1)
y = df[TARGET]

# =======================================================
# TRAIN TEST SPLIT
# =======================================================

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

# =======================================================
# FEATURE SCALING
# =======================================================

scaler = StandardScaler()

X_train = scaler.fit_transform(X_train)
X_test = scaler.transform(X_test)

# =======================================================
# MODELS
# =======================================================

models = {

    "Logistic_Regression":
        LogisticRegression(max_iter=1000),

    "Decision_Tree":
        DecisionTreeClassifier(random_state=42),

    "KNN":
        KNeighborsClassifier(n_neighbors=5),

    "Naive_Bayes":
        GaussianNB(),

    "SVM":
        SVC(
            probability=True,
            random_state=42
        )
}

# =======================================================
# TRAIN AND EVALUATE
# =======================================================

results = []

for model_name, model in models.items():

    print("\nTraining:", model_name)

    model.fit(X_train, y_train)

    y_pred = model.predict(X_test)

    y_prob = model.predict_proba(
        X_test
    )[:, 1]

    accuracy = accuracy_score(
        y_test,
        y_pred
    )

    precision = precision_score(
        y_test,
        y_pred
    )

    recall = recall_score(
        y_test,
        y_pred
    )

    f1 = f1_score(
        y_test,
        y_pred
    )

    auc = roc_auc_score(
        y_test,
        y_prob
    )

    mcc = matthews_corrcoef(
        y_test,
        y_pred
    )

    results.append([
        model_name,
        accuracy,
        auc,
        precision,
        recall,
        f1,
        mcc
    ])

    # ===================================================
    # CONFUSION MATRIX
    # ===================================================

    cm = confusion_matrix(
        y_test,
        y_pred
    )

    plt.figure(figsize=(6, 5))

    sns.heatmap(
        cm,
        annot=True,
        fmt="d",
        cmap="Blues"
    )

    plt.title(
        f"{model_name} Confusion Matrix"
    )

    plt.xlabel("Predicted")
    plt.ylabel("Actual")

    plt.tight_layout()

    plt.savefig(
        f"confusion_matrices/{model_name}_CM.png"
    )

    plt.close()

    # ===================================================
    # CLASSIFICATION REPORT
    # ===================================================

    report = classification_report(
        y_test,
        y_pred,
        output_dict=True
    )

    report_df = pd.DataFrame(
        report
    ).transpose()

    report_df.to_csv(
        f"classification_reports/{model_name}_report.csv"
    )

# =======================================================
# RESULTS TABLE
# =======================================================

results_df = pd.DataFrame(
    results,
    columns=[
        "Model",
        "Accuracy",
        "AUC",
        "Precision",
        "Recall",
        "F1 Score",
        "MCC"
    ]
)

results_df = results_df.sort_values(
    by="Accuracy",
    ascending=False
)

# =======================================================
# SAVE RESULTS
# =======================================================

results_df.to_csv(
    "results/model_comparison.csv",
    index=False
)

results_df.to_excel(
    "results/model_comparison.xlsx",
    index=False
)

# =======================================================
# PRINT RESULTS
# =======================================================

print("\n")
print("=" * 60)
print("FINAL MODEL COMPARISON")
print("=" * 60)

print(results_df.round(4))

print("\nBest Model:")

print(
    results_df.iloc[0]["Model"]
)

print("\nFiles Generated Successfully!")